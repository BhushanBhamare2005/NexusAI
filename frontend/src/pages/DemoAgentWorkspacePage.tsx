import { useState } from "react";
import { api } from "../services/api";
import ChatWindow from "../components/agent/ChatWindow";
import { Card } from "../components/ui/card";
import type { AgentMessage } from "../types/agent";

export default function DemoAgentWorkspacePage() {
  const [messages, setMessages] = useState<AgentMessage[]>([]);
  const [isSending, setIsSending] = useState(false);

  const send = async (text: string) => {
    const timestamp = new Date().toISOString();
    setMessages((current) => [
      ...current,
      {
        id: `${Date.now()}-user`,
        role: "user",
        content: text,
        timestamp,
      },
    ]);
    setIsSending(true);
    try {
      const { data } = await api.post<{ answer: string }>("/demo/ai-teammate", {
        message: text,
      });
      setMessages((current) => [
        ...current,
        {
          id: `${Date.now()}-ai`,
          role: "agent",
          content: data.answer,
          timestamp: new Date().toISOString(),
        },
      ]);
    } catch (reason) {
      setMessages((current) => [
        ...current,
        {
          id: `${Date.now()}-error`,
          role: "system",
          content:
            reason instanceof Error
              ? reason.message
              : "The AI request failed. Please try again.",
          timestamp: new Date().toISOString(),
        },
      ]);
    } finally {
      setIsSending(false);
    }
  };

  return (
    <div className="space-y-5">
      <div>
        <p className="text-xs font-medium uppercase tracking-wide text-nexus-accent">
          Restricted demo sandbox
        </p>
        <h1 className="mt-1 text-2xl font-semibold text-white">AI Teammate</h1>
        <p className="mt-1 text-sm text-nexus-muted">
          Ask Gemini for payment operations guidance. This demo cannot access
          live transactions or operational tools.
        </p>
      </div>
      <Card className="border-nexus-warn/30 bg-nexus-warn/5">
        <p className="text-sm text-nexus-warn">
          AI answers are generated by Gemini. They are general guidance only;
          no transaction lookup, refund, notification, or other real action is
          performed.
        </p>
      </Card>
      <div className="grid min-h-[32rem] gap-4 xl:grid-cols-[1.2fr_0.8fr]">
        <ChatWindow
          messages={messages}
          onSend={(text) => void send(text)}
          disabled={isSending}
        />
        <Card>
          <h2 className="text-sm font-semibold text-white">
            Safe demo prompts
          </h2>
          <ul className="mt-3 list-disc space-y-2 pl-4 text-sm text-nexus-muted">
            <li>How should I investigate a delayed payment?</li>
            <li>What details should I check before escalating a refund?</li>
            <li>How do I handle a duplicate notification report?</li>
          </ul>
          <p className="mt-4 border-t border-nexus-border pt-3 text-xs text-nexus-muted">
            For real AI investigations, sign in with an authorized operational
            Agent account.
          </p>
          <p className="mt-2 text-xs text-nexus-warn">
            Do not enter passwords, one-time codes, payment card details, or
            private customer information.
          </p>
        </Card>
      </div>
    </div>
  );
}
